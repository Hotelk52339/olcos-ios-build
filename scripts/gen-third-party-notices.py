#!/usr/bin/env python3
"""Regenerate App/Licenses/third-party-go.txt: the licence texts of every Go
module linked into App/Mobile.xcframework.

The framework binds the olcrtc core, gomobile/tunstack and olcos-core's xray
engine; their dependencies (pion, xray-core, outline-sdk, …) ship inside the
app, and their licences require the notices to travel with it. This lists the
modules the bound packages actually import for iOS (`go list -deps`, not the
whole build list), finds each module's licence and notice files in the module
cache, and writes them out in module order. The core itself has its own files
(App/Licenses/olcrtc-*.txt), copied verbatim from the submodule.

Run after any change to the submodules or gomobile/go.mod:

    python3 scripts/gen-third-party-notices.py

Needs Go (the version gomobile/go.mod names) and network for the module cache.
"""
import os
import re
import subprocess
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
WRAPPER = ROOT / "gomobile"
OUT = ROOT / "App" / "Licenses" / "third-party-go.txt"
PACKAGES = [
    "github.com/openlibrecommunity/olcrtc/mobile",
    "./tunstack",
    "github.com/Hotelk52339/olcos-core/olcos",
]
# Modules that are this project or have their own bundled files.
SKIP = {
    "github.com/openlibrecommunity/olcrtc-ios/gomobile",
    "github.com/openlibrecommunity/olcrtc",
    "github.com/Hotelk52339/olcos-core",
}
LICENSE_NAME = re.compile(r"^(licen[cs]e|copying|notice|patents)([.-].*)?$", re.IGNORECASE)


def go(*args):
    env = dict(os.environ, GOOS="ios", GOARCH="arm64", CGO_ENABLED="1", GOFLAGS="-mod=mod")
    return subprocess.run(["go", *args], cwd=WRAPPER, env=env, text=True,
                          capture_output=True, check=True).stdout


def main():
    sum_existed = (WRAPPER / "go.sum").exists()
    try:
        go("mod", "tidy")
        listing = go("list", "-deps", "-f",
                     "{{with .Module}}{{.Path}}\t{{.Version}}\t{{.Dir}}{{end}}", *PACKAGES)
    finally:
        # go.sum is generated by the build, not committed.
        if not sum_existed:
            (WRAPPER / "go.sum").unlink(missing_ok=True)
    modules = {}
    for line in listing.splitlines():
        if not line.strip():
            continue
        path, version, directory = line.split("\t")
        if path in SKIP:
            continue
        modules[path] = (version, Path(directory))
    sections = []
    missing = []
    # A licence text printed once is referenced afterwards: dozens of modules
    # carry the identical Apache-2.0 body.
    first_seen = {}
    for path in sorted(modules):
        version, directory = modules[path]
        files = sorted(p for p in directory.iterdir() if p.is_file() and LICENSE_NAME.match(p.name))
        if not files:
            missing.append(path)
            continue
        body = []
        for f in files:
            text = f.read_text(encoding="utf-8", errors="replace").replace("\r\n", "\n").strip()
            if text in first_seen:
                body.append(f"--- {f.name} --- identical to {first_seen[text]}")
            else:
                first_seen[text] = f"{f.name} of {path}"
                body.append(f"--- {f.name} ---\n{text}")
        sections.append(f"{'=' * 72}\n{path} {version}\n{'=' * 72}\n" + "\n\n".join(body))
    header = ("Third-party Go modules in olcOS (App/Mobile.xcframework).\n"
              "Generated by scripts/gen-third-party-notices.py — do not edit by hand.\n"
              f"{len(sections)} modules.\n")
    if missing:
        header += "No licence file found in the module for: " + ", ".join(missing) + "\n"
    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text(header + "\n" + "\n\n".join(sections) + "\n", encoding="utf-8", newline="\n")
    print(f"wrote {OUT.relative_to(ROOT)}: {len(sections)} modules"
          + (f", {len(missing)} without a licence file" if missing else ""))
    write_swift_notices()
    return 0


# Swift packages linked into the app: Citadel (project.yml) and what it pulls
# in. Their licence and NOTICE files are read from GitHub at their default
# branch; re-check this list when project.yml's packages change.
SWIFT_PACKAGES = [
    "orlandos-nl/Citadel",
    "Wellz26/swift-nio-ssh",
    "apple/swift-nio",
    "apple/swift-log",
    "apple/swift-crypto",
    "apple/swift-asn1",
    "apple/swift-atomics",
    "apple/swift-collections",
    "apple/swift-system",
    "attaswift/BigInt",
    "mtynior/ColorizeSwift",
]
SWIFT_OUT = ROOT / "App" / "Licenses" / "third-party-swift.txt"


def fetch(url):
    import urllib.error
    import urllib.request
    try:
        with urllib.request.urlopen(url, timeout=20) as response:
            return response.read().decode("utf-8", errors="replace").replace("\r\n", "\n").strip()
    except urllib.error.HTTPError as error:
        if error.code == 404:
            return None
        raise


def write_swift_notices():
    sections = []
    first_seen = {}
    for repo in SWIFT_PACKAGES:
        body = []
        for name in ("LICENSE", "LICENSE.txt", "LICENSE.md", "NOTICE", "NOTICE.txt"):
            text = fetch(f"https://raw.githubusercontent.com/{repo}/HEAD/{name}")
            if not text:
                continue
            if text in first_seen:
                body.append(f"--- {name} --- identical to {first_seen[text]}")
            else:
                first_seen[text] = f"{name} of {repo}"
                body.append(f"--- {name} ---\n{text}")
        if not body:
            raise SystemExit(f"no licence file found for {repo}")
        sections.append(f"{'=' * 72}\n{repo}\n{'=' * 72}\n" + "\n\n".join(body))
    header = ("Swift packages in olcOS.\n"
              "Generated by scripts/gen-third-party-notices.py — do not edit by hand.\n")
    SWIFT_OUT.write_text(header + "\n" + "\n\n".join(sections) + "\n", encoding="utf-8", newline="\n")
    print(f"wrote {SWIFT_OUT.relative_to(ROOT)}: {len(sections)} packages")


if __name__ == "__main__":
    sys.exit(main())
