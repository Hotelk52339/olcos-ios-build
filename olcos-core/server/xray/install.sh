#!/usr/bin/env bash
# olcos-core: install an Xray VLESS + REALITY + XTLS-Vision server in Podman,
# or adopt the one already on this host.
#
# The olcOS app uploads this script over SSH and runs it as root; it can be run
# by hand the same way. One deployment per host: an existing olcos-xray-*
# deployment is adopted (started if it is stopped, its link reported) instead
# of a second server being installed on the same port.
#
# Design (docs/HANDOFF.md §4):
#   * official image ghcr.io/xtls/xray-core, distroless, uid 65532, reads
#     /usr/local/etc/xray/*.json in lexical order (-confdir);
#   * pinned tag (OLCOS_XRAY_TAG), never a floating `latest` on a server;
#   * keys generated by one-shot containers (`xray uuid`, `xray x25519`) and
#     parsed by LABEL, not by line number (v26.7+ prints an extra Hash32 line);
#   * the REALITY target must pass `xray tls ping`: TLS 1.3, H2, a certificate
#     below the 8192-byte REALITY record limit (Xray-core #6402), and not a
#     *.ru/*.ir/*.cn/Apple/Microsoft host (Xray-core PR #6508). Without
#     OLCOS_XRAY_TARGET the first candidate of OLCOS_XRAY_TARGETS that passes
#     is used;
#   * `--restart=always` plus podman-restart.service, so the server comes back
#     after a reboot.
#
# Environment:
#   OLCOS_XRAY_ID        deployment id (default: random 8 hex chars)
#   OLCOS_XRAY_PORT      listen port (default 443)
#   OLCOS_XRAY_TARGET    REALITY target host[:443]; empty = first passing candidate
#   OLCOS_XRAY_TARGETS   comma-separated candidates for that (default below)
#   OLCOS_XRAY_SNI       SNI list, comma separated (default: target host)
#   OLCOS_XRAY_TAG       image tag (default 26.3.27 = current non-pre-release)
#   OLCOS_XRAY_NAME      client name (default olcOS)
#   OLCOS_XRAY_HOST      address written into the link (default: public IPv4)
#   OLCOS_XRAY_ADOPT     0 = install a new deployment even if one exists (default 1)
#   OLCOS_XRAY_PREFIX    parent directory of the deployment (default /opt)
#   OLCOS_XRAY_BBR       1 to enable BBR + fq via sysctl (default 0)
#   OLCOS_XRAY_ALLOW_NOSNI  1 to also accept clients that send no SNI (adds ""
#                        to serverNames; the target must itself answer without
#                        SNI, which the probe below verifies)
#
# Output, one KEY=VALUE per line on stdout (progress goes to stderr):
#   OLCOS_XRAY_URI=vless://…  OLCOS_XRAY_CONTAINER=…  OLCOS_XRAY_TARGET=…
#   OLCOS_XRAY_ADOPTED=0|1 — or OLCOS_XRAY_ERROR=<reason> and a non-zero exit.
set -euo pipefail

IMAGE_BASE="ghcr.io/xtls/xray-core"
TAG="${OLCOS_XRAY_TAG:-26.3.27}"
IMAGE="${IMAGE_BASE}:${TAG}"
ID="${OLCOS_XRAY_ID:-$(od -An -N8 -tx1 /dev/urandom | tr -d ' \n' | cut -c1-8)}"
PORT="${OLCOS_XRAY_PORT:-443}"
TARGET="${OLCOS_XRAY_TARGET:-}"
TARGET_HOST=""
NAME="${OLCOS_XRAY_NAME:-olcOS}"
PREFIX="${OLCOS_XRAY_PREFIX:-/opt}"
# Non-CDN sites checked by hand from an NL VPS (docs/HANDOFF.md, M1) first,
# then targets other installers ship by default. Each one still has to pass
# probe_target from this server before it is used.
DEFAULT_TARGETS="www.transip.nl,www.nlnet.nl,dl.google.com,www.googletagmanager.com,addons.mozilla.org"
ROOT="${PREFIX}/olcos-xray-${ID}"
CONF="${ROOT}/config"
KEYS="${ROOT}/keys"
CONTAINER="olcos-xray-${ID}"

log() { printf '[olcos-xray] %s\n' "$*" >&2; }
die() { log "ERROR: $*"; printf 'OLCOS_XRAY_ERROR=%s\n' "$*"; exit 1; }

emit() {
  printf 'OLCOS_XRAY_URI=%s\n' "$1"
  printf 'OLCOS_XRAY_CONTAINER=%s\n' "$2"
  printf 'OLCOS_XRAY_TARGET=%s\n' "$3"
  printf 'OLCOS_XRAY_ADOPTED=%s\n' "$4"
}

[[ "$(id -u)" == "0" ]] || die "run as root: Podman has to publish port ${PORT}"
[[ "$ID" =~ ^[a-z0-9]+$ ]] || die "OLCOS_XRAY_ID must be lowercase letters and digits"

# --- tools ---------------------------------------------------------------------
TOOLS=(podman curl openssl python3 ss)
missing_tools() {
  local t
  for t in "${TOOLS[@]}"; do command -v "$t" >/dev/null 2>&1 || printf '%s ' "$t"; done
}
MISSING="$(missing_tools)"
if [[ -n "$MISSING" ]]; then
  log "installing: ${MISSING}"
  if command -v apt-get >/dev/null 2>&1; then
    DEBIAN_FRONTEND=noninteractive apt-get update -qq >/dev/null 2>&1 || true
    DEBIAN_FRONTEND=noninteractive apt-get install -y -qq podman curl openssl python3 iproute2 >/dev/null 2>&1 \
      || die "apt-get could not install: ${MISSING}"
  elif command -v dnf >/dev/null 2>&1; then
    dnf install -y -q podman curl openssl python3 iproute >/dev/null 2>&1 || die "dnf could not install: ${MISSING}"
  elif command -v yum >/dev/null 2>&1; then
    yum install -y -q podman curl openssl python3 iproute >/dev/null 2>&1 || die "yum could not install: ${MISSING}"
  else
    die "missing ${MISSING}and there is no apt-get, dnf or yum to install it"
  fi
  MISSING="$(missing_tools)"
  [[ -z "$MISSING" ]] || die "still missing after the package install: ${MISSING}"
fi

# --- adopt the deployment already on this host ------------------------------------
if [[ "${OLCOS_XRAY_ADOPT:-1}" == "1" ]]; then
  EXISTING="$(podman ps -a --format '{{.Names}}' 2>/dev/null | grep -E '^olcos-xray-[a-z0-9]+$' | head -n1 || true)"
  if [[ -n "$EXISTING" ]]; then
    OLD_ROOT="${PREFIX}/${EXISTING}"
    LINK="$(head -n1 "${OLD_ROOT}/keys/share.vless" 2>/dev/null | tr -d '\r' || true)"
    [[ "$LINK" == vless://* ]] \
      || die "${EXISTING} exists but ${OLD_ROOT}/keys/share.vless holds no link; remove it with server/xray/uninstall.sh first"
    if [[ "$(podman inspect --format '{{.State.Running}}' "$EXISTING" 2>/dev/null || true)" != "true" ]]; then
      log "starting ${EXISTING}"
      podman start "$EXISTING" >/dev/null || die "could not start ${EXISTING}"
    fi
    systemctl enable podman-restart.service >/dev/null 2>&1 || true
    OLD_TARGET="$(grep -o '"target": *"[^"]*"' "${OLD_ROOT}/config/10_inbound.json" 2>/dev/null \
                  | head -n1 | sed 's/.*"\([^"]*\)"$/\1/' || true)"
    log "adopted ${EXISTING}"
    emit "$LINK" "$EXISTING" "$OLD_TARGET" 1
    exit 0
  fi
fi

# --- port availability -----------------------------------------------------------
if ss -ltnH "sport = :${PORT}" | grep -q .; then
  die "TCP port ${PORT} is already in use"
fi

# --- pull image ------------------------------------------------------------------
log "pulling ${IMAGE}"
podman pull -q "${IMAGE}" >/dev/null || die "could not pull ${IMAGE}"

xray() { podman run --rm "${IMAGE}" "$@"; }

# --- REALITY target ------------------------------------------------------------------
# Output format of `xray tls ping` (26.3.27):
#   Using IP:  1.2.3.4:443
#   Pinging without SNI / Handshake succeeded|Handshake failure: ...
#   TLS Version: ... TLS 1.3
#   Certificate chain's total length: 6476 (certs count: 2)
# The verdict is the exit status; the ping output is kept in /tmp for the log.
probe_target() {
  local host="$1" out cert ip alpn
  case "$host" in
    *.ru|*.ir|*.cn|*apple.com|*icloud.com|*microsoft.com|*live.com|*office.com)
      log "target ${host}: on the high-risk list (Xray-core PR #6508)"; return 1 ;;
  esac
  out="$(xray tls ping "$host" 2>&1 || true)"
  printf '%s\n' "$out" > "/tmp/olcos-xray-tlsping-${host}.txt"
  grep -q 'TLS 1.3' <<<"$out" || { log "target ${host}: no TLS 1.3"; return 1; }
  cert="$(grep -m1 'total length' <<<"$out" | grep -oE '[0-9]+ \(' | grep -oE '[0-9]+' || true)"
  if [[ -n "$cert" && "$cert" -ge 8192 ]]; then
    log "target ${host}: certificate of ${cert} bytes exceeds the REALITY 8192-byte limit (#6402)"; return 1
  fi
  ip="$(grep -m1 'Using IP' <<<"$out" | awk '{print $3}' | sed 's/:443$//' || true)"
  if [[ -n "$ip" ]]; then
    alpn="$(timeout 8 openssl s_client -connect "${ip}:443" -servername "$host" -alpn h2 </dev/null 2>/dev/null \
            | grep -i 'ALPN protocol' | awk '{print $NF}' || true)"
    [[ "$alpn" == "h2" ]] || { log "target ${host}: no H2 (ALPN '${alpn}')"; return 1; }
  fi
  if [[ "${OLCOS_XRAY_ALLOW_NOSNI:-0}" == "1" ]]; then
    grep -A1 'without SNI' <<<"$out" | grep -q 'Handshake succeeded' \
      || { log "target ${host}: rejects handshakes without SNI"; return 1; }
  fi
  return 0
}

if [[ -n "$TARGET" ]]; then
  TARGET_HOST="${TARGET%%:*}"
  [[ "$TARGET" == *:* ]] || TARGET="${TARGET}:443"
  [[ "${TARGET##*:}" == "443" ]] || die "target port must be 443"
  probe_target "$TARGET_HOST" || die "${TARGET_HOST} does not qualify as a REALITY target (see the log above)"
else
  IFS=',' read -r -a CANDIDATES <<<"${OLCOS_XRAY_TARGETS:-$DEFAULT_TARGETS}"
  for candidate in "${CANDIDATES[@]}"; do
    candidate="$(tr -d '[:space:]' <<<"$candidate")"
    [[ -n "$candidate" ]] || continue
    log "probing target ${candidate}"
    if probe_target "$candidate"; then
      TARGET_HOST="$candidate"
      break
    fi
  done
  [[ -n "$TARGET_HOST" ]] || die "no camouflage site passed the REALITY checks from this server; set OLCOS_XRAY_TARGET"
  TARGET="${TARGET_HOST}:443"
fi
log "target ${TARGET}"
SNI="${OLCOS_XRAY_SNI:-$TARGET_HOST}"
if [[ "${OLCOS_XRAY_ALLOW_NOSNI:-0}" == "1" ]]; then
  SNI="${SNI},"
fi

# --- keys ----------------------------------------------------------------------
umask 077
mkdir -p "${CONF}" "${KEYS}"
UUID="$(xray uuid | tr -d '\r\n[:space:]')"
[[ "$UUID" =~ ^[0-9a-f-]{36}$ ]] || die "unexpected uuid output: ${UUID}"
X25519_OUT="$(xray x25519)"
# Labels seen in the wild: "Private key:", "PrivateKey:", "Public key:",
# "Password:", "Password (PublicKey):"; 26.7+ also prints "Hash32:". Match by
# normalized label, never by line number.
label_value() {
  awk -F': *' -v want="$1" '{ k=tolower($1); gsub(/[^a-z]/, "", k); if (k == want) { print $2; exit } }' <<<"$X25519_OUT" | tr -d '\r[:space:]'
}
PRIV="$(label_value privatekey)"
PUB="$(label_value passwordpublickey)"
[[ -n "$PUB" ]] || PUB="$(label_value password)"
[[ -n "$PUB" ]] || PUB="$(label_value publickey)"
[[ -n "$PRIV" && -n "$PUB" ]] || die "could not parse the x25519 output: $(tr '\n' '|' <<<"$X25519_OUT")"
SID="$(od -An -N8 -tx1 /dev/urandom | tr -d ' \n')"
printf '%s\n' "$UUID" > "${KEYS}/uuid"
printf '%s\n' "$PRIV" > "${KEYS}/x25519.private"
printf '%s\n' "$PUB"  > "${KEYS}/x25519.public"
printf '%s\n' "$SID"  > "${KEYS}/shortid"

# --- config ---------------------------------------------------------------------
# Kept in sync with engine/xray.RenderServerConfig (Go is the reference).
SNI_JSON="$(python3 - "$SNI" <<'PY'
import json, sys
names=[s.strip() for s in sys.argv[1].split(",")]
print(json.dumps([n for i,n in enumerate(names) if n or i==len(names)-1]))
PY
)"
cat > "${CONF}/10_inbound.json" <<JSON
{
  "log": { "loglevel": "warning" },
  "inbounds": [{
    "tag": "vless-in", "listen": "0.0.0.0", "port": ${PORT}, "protocol": "vless",
    "settings": {
      "clients": [{ "id": "${UUID}", "flow": "xtls-rprx-vision", "email": "${NAME}" }],
      "decryption": "none"
    },
    "streamSettings": {
      "network": "tcp", "security": "reality",
      "realitySettings": {
        "target": "${TARGET}",
        "serverNames": ${SNI_JSON},
        "privateKey": "${PRIV}",
        "shortIds": ["${SID}"],
        "maxTimeDiff": 60000
      }
    },
    "sniffing": { "enabled": true, "destOverride": ["http", "tls", "quic"] }
  }],
  "outbounds": [
    { "tag": "direct", "protocol": "freedom" },
    { "tag": "block", "protocol": "blackhole" }
  ]
}
JSON
chown -R 65532:65532 "${CONF}"
chmod 750 "${CONF}"; chmod 640 "${CONF}"/*.json

# --- test config, run container ---------------------------------------------------
# stdout carries only the KEY=VALUE result lines, so the check reports to stderr.
podman run --rm -v "${CONF}:/usr/local/etc/xray:ro,Z" "${IMAGE}" run -test -confdir /usr/local/etc/xray/ >&2 \
  || die "xray rejected the generated config"

if [[ "${OLCOS_XRAY_BBR:-0}" == "1" ]]; then
  printf 'net.core.default_qdisc=fq\nnet.ipv4.tcp_congestion_control=bbr\n' > /etc/sysctl.d/99-olcos-bbr.conf
  sysctl -p /etc/sysctl.d/99-olcos-bbr.conf >/dev/null || log "sysctl for BBR failed (non-fatal)"
fi

podman rm -f "${CONTAINER}" >/dev/null 2>&1 || true
# The image runs as uid 65532; inside the container's network namespace binding
# a port below 1024 needs the namespaced sysctl below (no extra capabilities).
podman run -d --name "${CONTAINER}" --restart=always \
  --sysctl net.ipv4.ip_unprivileged_port_start=0 \
  -p "${PORT}:${PORT}/tcp" \
  -v "${CONF}:/usr/local/etc/xray:ro,Z" \
  "${IMAGE}" >/dev/null || die "podman could not start ${CONTAINER}"
# podman-restart.service starts restart-policy=always containers after a
# reboot; enable it on hosts where it is not enabled by default.
systemctl enable podman-restart.service >/dev/null 2>&1 || true
sleep 2
if ! podman ps --format '{{.Names}} {{.Status}}' | grep -q "^${CONTAINER} Up"; then
  LOGS="$(podman logs --tail 20 "${CONTAINER}" 2>&1 | tr '\n' ' ' || true)"
  podman rm -f "${CONTAINER}" >/dev/null 2>&1 || true
  die "container did not stay up: ${LOGS}"
fi

# --- firewall ----------------------------------------------------------------------
if command -v ufw >/dev/null 2>&1 && ufw status 2>/dev/null | grep -q '^Status: active'; then
  if ufw allow "${PORT}/tcp" >/dev/null 2>&1; then
    log "ufw: allowed ${PORT}/tcp"
  else
    log "ufw: could not open ${PORT}/tcp"
  fi
fi

# --- share link (Xray-core #716) ------------------------------------------------------
LINK_HOST="${OLCOS_XRAY_HOST:-}"
if [[ -z "$LINK_HOST" ]]; then
  LINK_HOST="$(curl -4fsS --max-time 5 https://api.ipify.org 2>/dev/null || hostname -I | awk '{print $1}')"
fi
[[ -n "$LINK_HOST" ]] || die "could not tell this server's public address; set OLCOS_XRAY_HOST"
case "$LINK_HOST" in
  *:*) LINK_HOST="[${LINK_HOST}]" ;;   # IPv6 literal
esac
FIRST_SNI="${SNI%%,*}"
LINK="vless://${UUID}@${LINK_HOST}:${PORT}?encryption=none&flow=xtls-rprx-vision&security=reality&sni=${FIRST_SNI}&fp=chrome&pbk=${PUB}&sid=${SID}&spx=%2F&type=tcp#${NAME}-${ID}"
printf '%s\n' "$LINK" > "${KEYS}/share.vless"
log "installed ${CONTAINER} (image ${IMAGE}); config ${CONF}; keys ${KEYS}"
emit "$LINK" "$CONTAINER" "$TARGET" 0
